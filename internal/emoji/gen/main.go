// Command gen regenerates internal/emoji/emoji.tsv from Unicode's data:
// emoji-test.txt (every emoji and its name) and CLDR's English annotations
// (search keywords). A dev tool, run with `just emoji`; nothing fetches at
// runtime.
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"strings"
	"time"
)

const (
	emojiTestURL   = "https://unicode.org/Public/emoji/latest/emoji-test.txt"
	annotationsURL = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-annotations-full/annotations/en/annotations.json"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen <output emoji.tsv>")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	test, err := fetch(emojiTestURL)
	if err != nil {
		return err
	}
	ann, err := fetch(annotationsURL)
	if err != nil {
		return err
	}
	entries, version, err := parseEmojiTest(strings.NewReader(string(test)))
	if err != nil {
		return err
	}
	keywords, err := parseAnnotations(ann)
	if err != nil {
		return err
	}
	f, err := os.Create(out)
	if err != nil {
		return err
	}
	if err := write(f, entries, keywords, version); err != nil {
		return err
	}
	return f.Close()
}

func fetch(url string) ([]byte, error) {
	client := http.Client{Timeout: time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		return nil, fmt.Errorf("fetching %s: %w", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetching %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

type entry struct{ glyph, name string }

// parseEmojiTest reads emoji-test.txt: the fully-qualified emoji, minus
// skin-tone variants and the Component group (bare skin tones and hair),
// in Unicode's order (most common groups first). It also returns the data
// version from the "# Version:" header.
func parseEmojiTest(r io.Reader) (entries []entry, version string, err error) {
	sc := bufio.NewScanner(r)
	group := ""
	for sc.Scan() {
		line := sc.Text()
		switch {
		case strings.HasPrefix(line, "# Version:"):
			version = strings.TrimSpace(strings.TrimPrefix(line, "# Version:"))
			continue
		case strings.HasPrefix(line, "# group:"):
			group = strings.TrimSpace(strings.TrimPrefix(line, "# group:"))
			continue
		case group == "Component" || !strings.Contains(line, "; fully-qualified"):
			continue
		}
		codes, rest, _ := strings.Cut(line, ";")
		if skinToned(codes) {
			continue
		}
		_, comment, _ := strings.Cut(rest, "# ")
		// "😀 E1.0 grinning face"
		glyph, after, _ := strings.Cut(comment, " ")
		_, name, _ := strings.Cut(after, " ")
		if glyph != "" && name != "" {
			entries = append(entries, entry{glyph, name})
		}
	}
	return entries, version, sc.Err()
}

func skinToned(codes string) bool {
	for _, c := range strings.Fields(codes) {
		if c >= "1F3FB" && c <= "1F3FF" && len(c) == 5 {
			return true
		}
	}
	return false
}

// parseAnnotations reads CLDR's annotations.json: each emoji's "default"
// keywords, keyed by the emoji without variation selectors (CLDR omits
// U+FE0F where emoji-test.txt has it).
func parseAnnotations(data []byte) (map[string][]string, error) {
	var doc struct {
		Annotations struct {
			Annotations map[string]struct {
				Default []string `json:"default"`
			} `json:"annotations"`
		} `json:"annotations"`
	}
	if err := json.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("reading annotations: %w", err)
	}
	out := make(map[string][]string, len(doc.Annotations.Annotations))
	for k, v := range doc.Annotations.Annotations {
		out[bare(k)] = v.Default
	}
	return out, nil
}

// bare drops variation selectors, so "❤️" and "❤" are the same key.
func bare(s string) string { return strings.ReplaceAll(s, "️", "") }

func write(w io.Writer, entries []entry, keywords map[string][]string, version string) error {
	bw := bufio.NewWriter(w)
	fmt.Fprintf(bw, "# Generated by internal/emoji/gen (just emoji). Do not edit.\n")
	fmt.Fprintf(bw, "# Emoji %s from %s\n# Keywords from %s\n", version, emojiTestURL, annotationsURL)
	fmt.Fprintf(bw, "# Unicode data: Copyright © 1991-2026 Unicode, Inc. See UNICODE-LICENSE.\n")
	fmt.Fprintf(bw, "# glyph\tname\tkeyword|keyword|...\n")
	for _, e := range entries {
		kws := keywords[bare(e.glyph)]
		fmt.Fprintf(bw, "%s\t%s\t%s\n", e.glyph, e.name, strings.Join(kws, "|"))
	}
	return bw.Flush()
}
